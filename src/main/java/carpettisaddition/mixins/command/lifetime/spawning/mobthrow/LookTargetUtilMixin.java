package carpettisaddition.mixins.command.lifetime.spawning.mobthrow;

import carpettisaddition.commands.lifetime.interfaces.LifetimeTrackerTarget;
import carpettisaddition.commands.lifetime.spawning.MobThrowSpawningReason;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.ai.behavior.BehaviorUtils;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;
import net.minecraft.world.phys.Vec3;

@Mixin(BehaviorUtils.class)
public abstract class LookTargetUtilMixin
{
	@ModifyVariable(
			method = "throwItem(Lnet/minecraft/world/entity/LivingEntity;Lnet/minecraft/world/item/ItemStack;Lnet/minecraft/world/phys/Vec3;Lnet/minecraft/world/phys/Vec3;F)V",
			at = @At(
					value = "INVOKE",
					target = "Lnet/minecraft/world/level/Level;addFreshEntity(Lnet/minecraft/world/entity/Entity;)Z"
			)
	)
	private static ItemEntity lifetimeTracker_recordSpawning_mobThrow_common(
			ItemEntity itemEntity, LivingEntity entity, ItemStack stack,
			Vec3 targetLocation
	)
	{
		((LifetimeTrackerTarget) itemEntity).recordSpawning$TISCM(new MobThrowSpawningReason(entity.getType()));
		return itemEntity;
	}
}
